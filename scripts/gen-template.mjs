// Generate infra/template.yaml (AWS SAM) from the route table, so the
// deployed API can never drift from the code: every route in
// packages/core/src/api/app.js becomes an HttpApi event on its function,
// with the JWT authorizer exactly when the route needs a signed-in user.
//
//   node scripts/gen-template.mjs          write infra/template.yaml
//   node scripts/gen-template.mjs --check  fail if it is out of date (CI)

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { ROUTES, FUNCTIONS } from '../packages/core/src/api/app.js';

const out = fileURLToPath(new URL('../infra/template.yaml', import.meta.url));

const fnNames = { catalog: 'CatalogFunction', shop: 'ShopFunction', provider: 'ProviderFunction', admin: 'AdminFunction', webhook: 'WebhookFunction' };
const pascal = (s) => s.replace(/[{}]/g, '').split(/[/_-]/).filter(Boolean).map((p) => p[0].toUpperCase() + p.slice(1)).join('');

function events(fn) {
  return ROUTES.filter((r) => r.fn === fn).map((r) => {
    const name = `${r.method[0]}${r.method.slice(1).toLowerCase()}${pascal(r.path) || 'Root'}`;
    return `        ${name}:
          Type: HttpApi
          Properties:
            ApiId: !Ref Api
            Method: ${r.method}
            Path: ${r.path}${r.auth ? '' : `
            Auth:
              Authorizer: NONE`}`;
  }).join('\n');
}

function httpFunction(fn) {
  const meta = FUNCTIONS[fn];
  const policies = {
    catalog: ['      - DynamoDBReadPolicy:\n          TableName: !Ref Table'],
    shop: ['      - DynamoDBCrudPolicy:\n          TableName: !Ref Table', '      - S3ReadPolicy:\n          BucketName: !Ref Bucket'],
    provider: ['      - DynamoDBCrudPolicy:\n          TableName: !Ref Table', '      - S3WritePolicy:\n          BucketName: !Ref Bucket'],
    admin: ['      - DynamoDBCrudPolicy:\n          TableName: !Ref Table', `      - Statement:
          - Effect: Allow
            Action: [cognito-idp:AdminDisableUser, cognito-idp:AdminEnableUser, cognito-idp:AdminUserGlobalSignOut]
            Resource: !GetAtt UserPool.Arn`],
    webhook: ['      - DynamoDBCrudPolicy:\n          TableName: !Ref Table'],
  }[fn];
  return `  ${fnNames[fn]}:
    Type: AWS::Serverless::Function
    Metadata:
      BuildMethod: esbuild
      BuildProperties:
        EntryPoints: [src/handler.js]
        Format: esm
        OutExtension: [.js=.mjs]
        Target: node22
        Minify: true
        Sourcemap: true
        External: ['@aws-sdk/*']
    Properties:
      Description: ${meta.description}
      CodeUri: ../services/aws
      Handler: handler.http
      MemorySize: ${meta.memoryMb}
      Environment:
        Variables:
          FUNCTION_GROUP: ${fn}
      Policies:
${policies.join('\n')}
      - AWSSecretsManagerGetSecretValuePolicy:
          SecretArn: !Ref Secrets
      Events:
${events(fn)}
`;
}

